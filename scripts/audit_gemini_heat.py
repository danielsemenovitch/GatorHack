"""Visual sanity check: render the exact same patch overlay placement as React Stage.

Uses the team's preexisting full-Gemini-blot example. A wholly AI image has
no ground-truth *local splice boundary*: this only verifies spatial geometry
and visualizes where the experimental CNN allocates its heat.
"""
from __future__ import annotations

import base64
import io
import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

from btw.report import analyze

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "examples" / "gemini_whole_blot.jpeg"
OUT = ROOT / "results" / "heat_overlay_audit"


def decode(url):
    return Image.open(io.BytesIO(base64.b64decode(url.split(",", 1)[1]))).convert("RGBA")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    data = SOURCE.read_bytes()
    original = Image.open(io.BytesIO(data)).convert("RGBA")
    report = analyze(data, SOURCE.name, blot_mode="auto", cnn_version="v3",
                     screening_policy="conservative")
    if len(report["figures"]) != 1:
        raise RuntimeError("Expected one whole AI blot source image")
    fig = report["figures"][0]
    if not fig["panels"]:
        raise RuntimeError("The whole-AI-blot example was not recognized as a blot")
    overlays = Image.new("RGBA", original.size, (0, 0, 0, 0))
    for panel in fig["panels"]:
        heat = decode(panel["heat"])
        if heat.size != (panel["w"], panel["h"]):
            raise AssertionError((heat.size, panel["w"], panel["h"]))
        if panel["x"] < 0 or panel["y"] < 0 or panel["x"] + panel["w"] > fig["width"] or panel["y"] + panel["h"] > fig["height"]:
            raise AssertionError("Heat overlay would lie outside its source figure")
        overlays.alpha_composite(heat, (panel["x"], panel["y"]))
    result = Image.alpha_composite(original, overlays)
    draw = ImageDraw.Draw(result)
    for panel in fig["panels"]:
        x, y, w, h = (panel[k] for k in ("x", "y", "w", "h"))
        draw.rectangle((x, y, x + w, y + h), outline="#de2874", width=2)
    strip = Image.new("RGB", (original.width * 2, original.height), "white")
    strip.paste(original.convert("RGB"), (0, 0))
    strip.paste(result.convert("RGB"), (original.width, 0))
    strip.save(OUT / "gemini_whole_blot_side_by_side.jpg", quality=91)
    info = {
        "source": str(SOURCE.relative_to(ROOT)),
        "source_size": list(original.size),
        "cnn_version": "v3",
        "screening_policy": "conservative",
        "analyzed_panels": len(fig["panels"]),
        "flagged_panels": report["summary"]["flagged_panels"],
        "threshold": report["summary"]["threshold"],
        "panels": [{k: p[k] for k in ("x", "y", "w", "h", "score", "flagged")} for p in fig["panels"]],
        "interpretation": "Geometry-only sanity audit. Whole image was generated by Gemini, so local CNN heat does not correspond to a known edit mask.",
    }
    (OUT / "gemini_heat_audit.json").write_text(json.dumps(info, indent=2))
    print(json.dumps(info, indent=2), flush=True)


if __name__ == "__main__":
    main()
